namespace Hermaeus.Core.Models;

public enum MediaKind { Image, Audio, Video }
public enum MediaGenerationProtocol { OpenAiCompatible, ComfyUi }

/// <summary>A single explicit generation. Endpoint and credential reference are frozen by the caller.</summary>
public sealed record MediaGenerationRequest(
    MediaGenerationProtocol Protocol,
    MediaKind Kind,
    string Endpoint,
    string Prompt,
    string Model = "",
    string SecretReference = "",
    string Voice = "alloy",
    string Size = "",
    int VideoSeconds = 4,
    string WorkflowJson = "");

public sealed record MediaGenerationProgress(string Status, string JobId = "");

/// <summary>Session-only generated bytes. SuggestedFileName is display/export guidance, never a local path.</summary>
public sealed record GeneratedMedia(string SuggestedFileName, string MediaType, byte[] Data);

public sealed record MediaGenerationResult(IReadOnlyList<GeneratedMedia> Files, string JobId = "");
